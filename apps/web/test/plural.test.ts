// Склонение числительных (`lib/plural.ts`) для подписей «В тренде»: «N играют»/
// «N игроков» — проверяем обе формы (три формы существительного, две — глагола)
// и исключение 11–14.
import { describe, expect, it } from "bun:test";
import { pluralize } from "../src/lib/plural";

describe("pluralize", () => {
  it("one — форма для 1 (и 21, 31…)", () => {
    expect(pluralize(1, "игрок", "игрока", "игроков")).toBe("игрок");
    expect(pluralize(21, "игрок", "игрока", "игроков")).toBe("игрок");
  });

  it("few — форма для 2–4 (и 22–24…)", () => {
    expect(pluralize(2, "игрок", "игрока", "игроков")).toBe("игрока");
    expect(pluralize(4, "игрок", "игрока", "игроков")).toBe("игрока");
    expect(pluralize(22, "игрок", "игрока", "игроков")).toBe("игрока");
  });

  it("many — форма для 0, 5–9 и 11–14", () => {
    expect(pluralize(0, "игрок", "игрока", "игроков")).toBe("игроков");
    expect(pluralize(5, "игрок", "игрока", "игроков")).toBe("игроков");
    expect(pluralize(9, "игрок", "игрока", "игроков")).toBe("игроков");
  });

  it("исключение 11–14 — «many», даже у «1» на конце (11)", () => {
    expect(pluralize(11, "игрок", "игрока", "игроков")).toBe("игроков");
    expect(pluralize(14, "игрок", "игрока", "игроков")).toBe("игроков");
  });

  it("глагол: few и many — одна форма («играют»)", () => {
    expect(pluralize(1, "играет", "играют", "играют")).toBe("играет");
    expect(pluralize(2, "играет", "играют", "играют")).toBe("играют");
    expect(pluralize(5, "играет", "играют", "играют")).toBe("играют");
  });
});
